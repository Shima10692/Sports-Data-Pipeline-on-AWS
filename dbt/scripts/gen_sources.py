"""Print dbt/models/staging/_sources.yml from the clean-zone schemas.

The clean-zone tables are defined once, in processing/glue/src/clean_zone. This
keeps the dbt sources in step with them. tests/test_dbt_sources.py fails on drift.

Run from the repo root:
    python dbt/scripts/gen_sources.py > dbt/models/staging/_sources.yml
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "processing" / "glue" / "src"))

from clean_zone.sources import TABLES  # noqa: E402
from clean_zone.table import PARTITION_COLUMN  # noqa: E402

# TheSportsDB needs an API key in Secrets Manager; its raw data is not loaded yet,
# so its tables do not exist in the Catalog. Add them when they do.
EXCLUDED_PREFIXES = ("thesportsdb_",)

# Snapshot tables: dt = download day, so dt says how old the newest copy is.
SNAPSHOT_TABLES = ("statsbomb_competitions", "statsbomb_matches", "jolpica_races")
FRESHNESS_WARN_DAYS = 8


def used_tables() -> list[str]:
    return [n for n in TABLES if not n.startswith(EXCLUDED_PREFIXES)]


def q(text: str) -> str:
    return json.dumps(text)  # a JSON string is a valid YAML double-quoted scalar


def render() -> str:
    out = [
        "# GENERATED by dbt/scripts/gen_sources.py from processing/glue/src/clean_zone. Do not hand-edit.",
        "# tests/test_dbt_sources.py fails if this file drifts from the clean-zone schemas.",
        "version: 2",
        "",
        "sources:",
        "  - name: clean",
        "    description: Clean-zone Parquet tables registered in the Glue Data Catalog by the raw-to-clean job.",
        "    schema: \"{{ var('lake_database', target.schema ~ '_lake') }}\"",
        "    tables:",
    ]
    for name in used_tables():
        t = TABLES[name]
        out.append(f"      - name: {name}")
        out.append(f"        description: {q(t.description)}")
        if name in SNAPSHOT_TABLES:
            out += [
                "        config:",
                "          loaded_at_field: \"cast(date_parse(dt, '%Y-%m-%d') as timestamp)\"",
                "          freshness:",
                f"            warn_after: {{count: {FRESHNESS_WARN_DAYS}, period: day}}",
            ]
        out.append("        columns:")
        for c in t.all_columns:
            out.append(f"          - name: {c.name}")
            out.append(f"            data_type: {q(c.parsed.ddl())}")
            if c.comment:
                out.append(f"            description: {q(c.comment)}")
        out += [
            f"          - name: {PARTITION_COLUMN}",
            '            data_type: "string"',
            '            description: "Partition: the raw-zone date= value (yyyy-mm-dd)."',
        ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render())
